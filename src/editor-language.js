export function languageInfo(path = "") {
  const ext = path.split(".").pop().toLowerCase();
  const types = {
    json: ["JSON", "json", 2],
    jsonc: ["JSONC", "json", 2],
    json5: ["JSON5", "json", 2],
    java: ["Java", "java", 4],
    js: ["JavaScript", "javascript", 2],
    jsx: ["JavaScript JSX", "javascript", 2],
    mjs: ["JavaScript", "javascript", 2],
    cjs: ["JavaScript", "javascript", 2],
    ts: ["TypeScript", "typescript", 2],
    tsx: ["TypeScript JSX", "typescript", 2],
    html: ["HTML", "html", 2],
    htm: ["HTML", "html", 2],
    css: ["CSS", "css", 2],
    scss: ["SCSS", "css", 2],
    less: ["Less", "css", 2],
    py: ["Python", "python", 4],
    sql: ["SQL", "sql", 2],
    md: ["Markdown", "markdown", 2],
    mdx: ["MDX", "markdown", 2],
    yaml: ["YAML", "yaml", 2],
    yml: ["YAML", "yaml", 2],
    xml: ["XML", "xml", 2],
    svg: ["SVG", "xml", 2],
  };
  const [label, mode, indent] = types[ext] || ["纯文本", "text", 2];
  return {
    label,
    mode,
    indent,
    ext,
    canFormat: [
      "json",
      "jsonc",
      "json5",
      "java",
      "js",
      "jsx",
      "mjs",
      "cjs",
      "ts",
      "tsx",
      "html",
      "htm",
      "css",
      "scss",
      "less",
      "md",
      "mdx",
      "yaml",
      "yml",
      "xml",
      "svg",
    ].includes(ext),
  };
}
